void Collect(Type t, string area, bool input)
{
    t = Nullable.GetUnderlyingType(t) ?? t;
    if (t.IsArray)
    {
        Collect(t.GetElementType()!, area, input);
        return;
    }
    if (t.IsGenericType)
    {
        foreach (var a in t.GetGenericArguments())
            Collect(a, area, input);
        if (!IsModel(t.GetGenericTypeDefinition()))
            return;
    }
    if (!IsModel(t) && !t.IsEnum)
        return;
    var def = t.IsGenericType ? t.GetGenericTypeDefinition() : t;
    if (input)
        inputTypes.Add(def);
    if (typeArea.ContainsKey(def))
        return;
    typeArea[def] = def.Namespace == "IKCO.ProductionFeasibility.Common" || def.Namespace?.StartsWith("Volo.") == true ? "Common"
        : def.Namespace == "IKCO.ProductionFeasibility.StoredProcedures.Results" ? area
        : AreaOfNamespace(def.Namespace!);
    if (def.IsEnum)
        return;
    foreach (var p in Props(def))
        Collect(p.PropertyType, area, input);
}

