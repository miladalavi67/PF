string? RuleFor(PropertyInfo p)
{
    var label = Label(p);
    var parts = new List<string>();
    var isList = p.PropertyType != typeof(string) && typeof(IEnumerable).IsAssignableFrom(p.PropertyType);
    if (p.GetCustomAttribute<RequiredAttribute>() != null && !isList)
        parts.Add($"required: \"«{label}» الزامی است\"");
    if (p.GetCustomAttribute<StringLengthAttribute>() is { } sl)
    {
        if (sl.MinimumLength > 0 && sl.MinimumLength == sl.MaximumLength)
        {
            parts.Add($"minLength: {{ value: {sl.MinimumLength}, message: \"«{label}» باید {sl.MinimumLength} کاراکتر باشد\" }}");
            parts.Add($"maxLength: {{ value: {sl.MaximumLength}, message: \"«{label}» باید {sl.MaximumLength} کاراکتر باشد\" }}");
        }
        else
        {
            if (sl.MinimumLength > 0)
                parts.Add($"minLength: {{ value: {sl.MinimumLength}, message: \"«{label}» حداقل {sl.MinimumLength} کاراکتر است\" }}");
            parts.Add($"maxLength: {{ value: {sl.MaximumLength}, message: \"«{label}» حداکثر {sl.MaximumLength} کاراکتر است\" }}");
        }
    }
    if (p.GetCustomAttribute<RangeAttribute>() is { } range)
    {
        var min = Convert.ToDouble(range.Minimum);
        var max = Convert.ToDouble(range.Maximum);
        var msg = max >= int.MaxValue ? $"«{label}» باید حداقل {min} باشد" : $"«{label}» باید بین {min} و {max} باشد";
        parts.Add($"min: {{ value: {min}, message: \"{msg}\" }}");
        if (max < int.MaxValue)
            parts.Add($"max: {{ value: {max}, message: \"{msg}\" }}");
    }
    if (p.GetCustomAttribute<RegularExpressionAttribute>() is { } re)
        parts.Add($"pattern: {{ value: /{re.Pattern.Replace("/", "\\/")}/, message: \"{(string.IsNullOrWhiteSpace(re.ErrorMessage) ? $"مقدار «{label}» معتبر نیست" : re.ErrorMessage)}\" }}");
    if (isList && p.GetCustomAttribute<MinLengthAttribute>() is { } ml && ml.Length > 0)
        parts.Add($"validate: (v: unknown) => (Array.isArray(v) && v.length >= {ml.Length}) || \"حداقل یک مورد برای «{label}» انتخاب کنید\"");
    if (isList && p.GetCustomAttribute<MaxLengthAttribute>() is { } xl)
        parts.Add($"maxLength: {{ value: {xl.Length}, message: \"تعداد «{label}» بیش از حد مجاز است\" }}");
    return parts.Count == 0 ? null : $"  {JsonName(p)}: {{ {string.Join(", ", parts)} }},";
}

string Label(PropertyInfo p)
{
    var s = Summary(PropKey(p));
    if (string.IsNullOrEmpty(s))
        return p.Name;
    s = Regex.Replace(s, @"\(.*?\)|<.*?>|[«»""]", string.Empty);
    s = s.Split('؛', '،', '.', ':')[0].Trim();
    return s.Length is 0 or > 40 ? p.Name : s;
}

string Ts(Type t, NullabilityInfo? info, string fromFile)
{
    var u = Nullable.GetUnderlyingType(t);
    if (u != null)
        return Ts(u, null, fromFile);
    if (t.IsGenericParameter)
        return t.Name;
    if (t == typeof(string) || t == typeof(char) || t == typeof(Guid) || t == typeof(DateTime) || t == typeof(DateTimeOffset) || t == typeof(TimeSpan) || t == typeof(byte[]))
        return "string";
    if (t == typeof(bool))
        return "boolean";
    if (t.IsPrimitive || t == typeof(decimal))
        return "number";
    if (t == typeof(object))
        return "unknown";
    if (t.IsGenericType && t.GetGenericTypeDefinition().Name.StartsWith("Dictionary") || t.IsGenericType && t.GetGenericTypeDefinition().Name.StartsWith("IDictionary") || t.IsGenericType && t.GetGenericTypeDefinition().Name.StartsWith("IReadOnlyDictionary"))
        return $"Record<string, {Wrap(Ts(t.GetGenericArguments()[1], info?.GenericTypeArguments.ElementAtOrDefault(1), fromFile), info?.GenericTypeArguments.ElementAtOrDefault(1))}>";
    if (t.IsArray)
        return Wrap(Ts(t.GetElementType()!, info?.ElementType, fromFile), info?.ElementType) + "[]";
    if (t.IsGenericType && typeof(IEnumerable).IsAssignableFrom(t) && !IsModel(t.GetGenericTypeDefinition()))
        return Wrap(Ts(t.GetGenericArguments()[0], info?.GenericTypeArguments.ElementAtOrDefault(0), fromFile), info?.GenericTypeArguments.ElementAtOrDefault(0)) + "[]";
    if (t.IsGenericType)
    {
        var def = t.GetGenericTypeDefinition();
        var name = def.Name.StartsWith("ListResultDto") ? "IListResultDto" : def.Name.StartsWith("PagedResultDto") ? "IPagedResultDto" : tsName[def];
        Reference(fromFile, def, name);
        return name + "<" + string.Join(", ", t.GetGenericArguments().Select((a, i) => Ts(a, info?.GenericTypeArguments.ElementAtOrDefault(i), fromFile))) + ">";
    }
    if (tsName.TryGetValue(t, out var n))
    {
        Reference(fromFile, t, n);
        return n;
    }
    return "unknown";
}

string Wrap(string ts, NullabilityInfo? info) =>
    info != null && info.ReadState == NullabilityState.Nullable && !ts.EndsWith("| null") ? $"({ts} | null)" : ts;

void Reference(string fromFile, Type def, string name)
{
    var target = def.Name.StartsWith("ListResultDto") || def.Name.StartsWith("PagedResultDto") ? "Common" : typeArea[def];
    if (target != fromFile)
        Import(fromFile, target, name);
}

void Import(string fromFile, string target, string name)
{
    if (!fileImports.TryGetValue(fromFile, out var set))
        fileImports[fromFile] = set = new SortedSet<(string, string)>();
    set.Add((target, name));
}

string TsRef(Type t, NullabilityInfo? info, SortedDictionary<string, SortedSet<string>> imports)
{
    var marker = "__service__";
    fileImports.Remove(marker);
    var ts = Ts(t, info, marker);
    if (fileImports.TryGetValue(marker, out var refs))
    {
        foreach (var (file, name) in refs)
        {
            if (!imports.TryGetValue(file, out var set))
                imports[file] = set = new SortedSet<string>();
            set.Add(name);
        }
        fileImports.Remove(marker);
    }
    return ts;
}

string? Summary(string key)
{
    if (!docs.TryGetValue(key, out var m))
        return null;
    var s = m.Element("summary");
    if (s == null)
        return null;
    var text = string.Concat(s.Nodes().Select(n => n is XElement e ? (e.Attribute("cref")?.Value.Split('.').Last() ?? e.Value) : n.ToString()));
    text = Regex.Replace(System.Net.WebUtility.HtmlDecode(text), @"\s+", " ").Trim();
    return text.Length == 0 ? null : text.Replace("*/", "*\\/");
}

static string PropKey(PropertyInfo p) => "P:" + (p.DeclaringType!.IsGenericType ? p.DeclaringType.GetGenericTypeDefinition().FullName : p.DeclaringType.FullName)!.Replace('+', '.') + "." + p.Name;

static string DocKey(MethodInfo m)
{
    var ps = m.GetParameters();
    var name = "M:" + m.DeclaringType!.FullName + "." + m.Name;
    return ps.Length == 0 ? name : name + "(" + string.Join(",", ps.Select(p => DocType(p.ParameterType))) + ")";
}

static string DocType(Type t)
{
    if (t.IsGenericType)
    {
        var def = t.GetGenericTypeDefinition().FullName!;
        return def[..def.IndexOf('`')] + "{" + string.Join(",", t.GetGenericArguments().Select(DocType)) + "}";
    }
    return t.FullName!.Replace('+', '.');
}

string JsonName(PropertyInfo p) =>
    p.GetCustomAttribute<System.Text.Json.Serialization.JsonPropertyNameAttribute>()?.Name ?? camel.ConvertName(p.Name);

static IEnumerable<PropertyInfo> Props(Type t) =>
    t.GetProperties(BindingFlags.Public | BindingFlags.Instance)
        .Where(p => p.GetIndexParameters().Length == 0 && p.GetCustomAttribute<System.Text.Json.Serialization.JsonIgnoreAttribute>() == null
                    && p.GetCustomAttribute<System.Text.Json.Serialization.JsonExtensionDataAttribute>() == null)
        .GroupBy(p => p.Name).Select(g => g.First());

// ردیف خروجی رویه (PfResultRow): نام ستون‌ها همان خروجی رویه است و ستون‌های تعریف‌نشده هم در JSON می‌آیند
static bool IsResultRow(Type t) => typeof(IKCO.ProductionFeasibility.Common.PfResultRow).IsAssignableFrom(t);

static Type? ResultRowOfList(Type? t) =>
    t is { IsGenericType: true } && t.GetGenericTypeDefinition().Name.StartsWith("ListResultDto") && IsResultRow(t.GetGenericArguments()[0])
        ? t.GetGenericArguments()[0]
        : null;

static bool IsModel(Type t) =>
    t.IsClass && t != typeof(string) && t != typeof(object)
    && (t.Namespace?.StartsWith("IKCO.ProductionFeasibility") == true || t.Name.StartsWith("EntityDto"))
    && !t.Name.StartsWith("ListResultDto") && !t.Name.StartsWith("PagedResultDto");

static bool IsSimple(Type t)
{
    t = Nullable.GetUnderlyingType(t) ?? t;
    return t.IsPrimitive || t.IsEnum || t == typeof(string) || t == typeof(decimal) || t == typeof(DateTime) || t == typeof(Guid);
}

static string BaseName(Type t) => t.IsGenericTypeDefinition ? t.Name[..t.Name.IndexOf('`')] : t.Name;

static string AreaOf(Type controller) => AreaOfNamespace(controller.Namespace!);

static string AreaOfNamespace(string ns)
{
    var parts = ns.Split('.');
    return parts.Length > 2 && parts[0] == "IKCO" ? parts[2] : parts[^1];
}

static string LowerFirst(string s) => s.Length == 0 ? s : char.ToLowerInvariant(s[0]) + s[1..];

string ColumnsConst(Type row) => LowerFirst(tsName[row].Substring(1)) + "Columns";

static void AddImport(SortedDictionary<string, SortedSet<string>> imports, string module, string name)
{
    if (!imports.TryGetValue(module, out var set))
        imports[module] = set = new SortedSet<string>();
    set.Add(name);
}

static string Combine(string a, string? b) =>
    string.IsNullOrEmpty(b) ? a.TrimEnd('/') : b.StartsWith('/') || b.StartsWith("~/") ? b.TrimStart('~', '/') : a.TrimEnd('/') + "/" + b;

static string ParamName(MethodInfo m, string routeName) =>
    m.GetParameters().FirstOrDefault(p => string.Equals(p.Name, routeName, StringComparison.OrdinalIgnoreCase))?.Name ?? routeName;

static string FunctionName(string method, string entity, HashSet<string> used)
{
    var name = method.EndsWith("Async") ? method[..^5] : method;
    var words = Regex.Matches(name, "[A-Z][a-z0-9]*|[A-Z]+(?![a-z])").Select(m => m.Value).ToList();
    var verb = words.Count > 0 ? words[0] : name;
    var rest = name[verb.Length..];
    var result = rest.Contains(entity, StringComparison.Ordinal) || rest.StartsWith(entity.TrimEnd('s'), StringComparison.Ordinal)
        ? LowerFirst(verb) + rest
        : LowerFirst(verb) + entity + rest;
    var unique = result;
    for (var i = 2; !used.Add(unique); i++)
        unique = result + i;
    return unique;
}

